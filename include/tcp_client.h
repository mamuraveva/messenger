#pragma once

#include "crypto.h"
#include <functional>
#include <string>

/**
 * @brief TCP-клиент для подключения к серверу и обмена сообщениями.
 *
 * Отвечает за установку соединения, обмен ключами,
 * шифрование и расшифровку сообщений, а также приём данных
 * от сервера в отдельном цикле.
 */
class TcpClient {
private:
  /** @brief Дескриптор TCP-сокета. */
  int socket = -1;

  /** @brief Объект для шифрования и расшифровки сообщений. */
  Crypto crypto_;

public:
  /**
   * @brief Обработчик входящих сообщений.
   *
   * Вызывается после успешного получения и расшифровки сообщения.
   */
  std::function<void(const std::string &)> on_message_;

  /**
   * @brief Запускает цикл приёма сообщений.
   *
   * Непрерывно получает сообщения от сервера до разрыва соединения.
   */
  void receive_loop();

  /**
   * @brief Создаёт TCP-сокет.
   *
   * @return true при успешном создании сокета.
   * @return false в случае ошибки.
   */
  bool create();

  /**
   * @brief Подключается к серверу.
   *
   * @param ip IP-адрес сервера.
   * @param port Порт сервера.
   * @return true при успешном подключении.
   * @return false в случае ошибки.
   */
  bool connect(const std::string &ip, int port);

  /**
   * @brief Выполняет обмен публичными ключами.
   *
   * После успешного выполнения создаются сессионные ключи
   * для защищённого обмена сообщениями.
   *
   * @return true если обмен ключами выполнен успешно.
   * @return false в случае ошибки.
   */
  bool do_handshake();

  /**
   * @brief Отправляет сообщение на сервер.
   *
   * Перед отправкой сообщение шифруется.
   *
   * @param msg Исходный текст сообщения.
   * @return true если сообщение отправлено.
   * @return false в случае ошибки.
   */
  bool send_message(const std::string &msg);

  /**
   * @brief Получает одно сообщение от сервера.
   *
   * Выполняет получение пакета, расшифровку и вызов обработчика.
   *
   * @return true если сообщение успешно получено.
   * @return false при разрыве соединения или ошибке.
   */
  bool receive_message();

  /**
   * @brief Получает сообщение и передаёт его через механизм сигналов.
   *
   * Используется GUI-версией клиента.
   *
   * @return true если сообщение успешно получено.
   * @return false при ошибке.
   */
  bool receive_message_signal();

  /**
   * @brief Закрывает соединение с сервером.
   *
   * @return true если соединение успешно закрыто.
   * @return false в случае ошибки.
   */
  bool close();
};