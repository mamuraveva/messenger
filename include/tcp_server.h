#pragma once

#include <mutex>
#include <string>
#include <utility>
#include <vector>

/**
 * @brief TCP-сервер для подключения клиентов и пересылки сообщений.
 *
 * Сервер принимает подключения, объединяет клиентов в пары,
 * выполняет обмен ключами между участниками пары и пересылает
 * зашифрованные сообщения только между ними.
 */
class TcpServer {
private:
  /** @brief Дескриптор серверного сокета. */
  int server_socket = -1;

  /**
   * @brief Список пар подключённых клиентов.
   *
   * Каждый элемент содержит два сокета клиентов,
   * которые могут обмениваться сообщениями друг с другом.
   */
  std::vector<std::pair<int, int>> pairs;

  /** @brief Мьютекс для синхронизации доступа к списку пар. */
  std::mutex clients_mutex;

public:
  bool start(int port);

  bool validatePort(int port);

  /**
   * @brief Принимает подключения клиентов.
   *
   * Ожидает подключения клиентов, объединяет их в пары,
   * выполняет обмен публичными ключами и запускает
   * потоки обработки сообщений.
   */
  void accept_clients();

  /**
   * @brief Обрабатывает сообщения одного клиента.
   *
   * Получает пакеты от клиента и пересылает их его собеседнику.
   *
   * @param client_socket Сокет клиента.
   */
  void handle_client(int client_socket);

  /**
   * @brief Пересылает сообщение собеседнику отправителя.
   *
   * Находит пару, в которой находится отправитель,
   * и передаёт сообщение второму участнику пары.
   *
   * @param data Передаваемый пакет данных.
   * @param sender_socket Сокет отправителя сообщения.
   */
  void broadcast_message(const std::vector<unsigned char> &data,
                         int sender_socket);
};